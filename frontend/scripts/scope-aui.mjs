// Official AUI styles are isolated to the artifact workspace; React owns events.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import postcss from 'postcss';
const root=new URL('../app/components/jira/',import.meta.url);
const source=readFileSync(new URL('aui-9.12.0.source.css',root),'utf8');
if(createHash('sha256').update(source).digest('hex')!=='7dc34591fb0373c68e3597988813c979d1c3cc2284644a7166cc3c9125b55cc2')throw Error('Unexpected AUI source');
const css=postcss.parse(source);
css.walkRules(rule=>{
 let parent=rule.parent;
 while(parent){if(parent.type==='atrule'&&/keyframes$/.test(parent.name))return;parent=parent.parent;}
 rule.selectors=rule.selectors.map(selector=>/^(html|body|:root)(?=[\s.#[:]|$)/.test(selector)?selector.replace(/^(html|body|:root)/,':where(.jira-dc-ui)').replace(/:where\(\.jira-dc-ui\)\s+body\b/,':where(.jira-dc-ui)'):':where(.jira-dc-ui) '+selector);
});
css.walkAtRules('font-face',rule=>{
 const value=rule.toString().includes('fonts/atlassian-icons.')?'atlassian-icons':'adgs-icons';
 rule.walkDecls('src',decl=>decl.remove());
 rule.append({prop:'src',value:`url("/vendor/aui-9.12.0/fonts/${value}.woff") format("woff")`});
});
css.walkComments(comment=>{if(comment.text.includes('sourceMappingURL'))comment.remove();});
writeFileSync(new URL('aui-9.12.0.scoped.css',root),'/* Generated by scripts/scope-aui.mjs; @atlassian/aui 9.12.0 Apache-2.0. */\n'+css.toString());
console.log('Scoped official AUI 9.12.0 to .jira-dc-ui');
