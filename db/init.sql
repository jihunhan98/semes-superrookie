CREATE TABLE requirement_impact_events (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY,
 project_id NUMBER NOT NULL,
 requirement_id NUMBER NOT NULL,
 input_hash VARCHAR2(64 CHAR) NOT NULL,
 context_hash VARCHAR2(64 CHAR) NOT NULL,
 is_current NUMBER(1) DEFAULT 1 NOT NULL,
 event_data CLOB NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT pk_req_impact_events PRIMARY KEY(id),
 CONSTRAINT fk_impact_event_project FOREIGN KEY(project_id) REFERENCES projects(id),
 CONSTRAINT fk_impact_event_req FOREIGN KEY(requirement_id) REFERENCES requirements(id)
);
CREATE INDEX ix_impact_project_current ON requirement_impact_events(project_id,is_current);
CREATE INDEX ix_impact_req_current ON requirement_impact_events(requirement_id,is_current);
CREATE TABLE requirement_impact_reads (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY,
 event_id NUMBER NOT NULL,
 user_id NUMBER NOT NULL,
 read_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT pk_req_impact_reads PRIMARY KEY(id),
 CONSTRAINT fk_impact_read_event FOREIGN KEY(event_id) REFERENCES requirement_impact_events(id),
 CONSTRAINT fk_impact_read_user FOREIGN KEY(user_id) REFERENCES users(id),
 CONSTRAINT uq_impact_read_user UNIQUE(event_id,user_id)
);
