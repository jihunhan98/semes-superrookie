-- 기존 DB에 추가할 질문·프로젝트 용어사전 테이블입니다. V007 적용 이후 한 번 실행합니다.
CREATE TABLE project_terms (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY,
 project_id NUMBER NOT NULL,
 name VARCHAR2(100 CHAR) NOT NULL,
 normalized_name VARCHAR2(200 CHAR) NOT NULL,
 definition CLOB NOT NULL,
 ai_definition CLOB,
 status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
 row_version NUMBER DEFAULT 0 NOT NULL,
 reviewed_by NUMBER,
 reviewed_at TIMESTAMP,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT pk_project_terms PRIMARY KEY(id),
 CONSTRAINT fk_project_term_project FOREIGN KEY(project_id) REFERENCES projects(id),
 CONSTRAINT uq_project_term_name UNIQUE(project_id,normalized_name),
 CONSTRAINT ck_project_term_status CHECK(status IN ('PENDING','CONFIRMED','DISMISSED'))
);
CREATE TABLE project_term_usages (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY,
 term_id NUMBER NOT NULL,
 requirement_id NUMBER NOT NULL,
 source_quote CLOB NOT NULL,
 CONSTRAINT pk_project_term_usages PRIMARY KEY(id),
 CONSTRAINT fk_term_usage_term FOREIGN KEY(term_id) REFERENCES project_terms(id),
 CONSTRAINT fk_term_usage_requirement FOREIGN KEY(requirement_id) REFERENCES requirements(id),
 CONSTRAINT uq_term_usage UNIQUE(term_id,requirement_id)
);
CREATE TABLE requirement_refinements (
 requirement_id NUMBER NOT NULL,
 content CLOB NOT NULL,
 revision NUMBER DEFAULT 0 NOT NULL,
 status VARCHAR2(20 CHAR) DEFAULT 'ANALYZING' NOT NULL,
 new_term_count NUMBER DEFAULT 0 NOT NULL,
 term_status VARCHAR2(20 CHAR) DEFAULT 'RULE_ONLY' NOT NULL,
 glossary_hash VARCHAR2(64 CHAR),
 CONSTRAINT pk_req_refinements PRIMARY KEY(requirement_id),
 CONSTRAINT fk_refinement_req FOREIGN KEY(requirement_id) REFERENCES requirements(id)
);
CREATE TABLE clarification_questions (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY,
 requirement_id NUMBER NOT NULL,
 fingerprint VARCHAR2(64 CHAR) NOT NULL,
 status VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL,
 question_data CLOB NOT NULL,
 answer CLOB,
 replacement CLOB,
 note CLOB,
 answered_by NUMBER,
 CONSTRAINT pk_clarification_questions PRIMARY KEY(id),
 CONSTRAINT fk_question_requirement FOREIGN KEY(requirement_id) REFERENCES requirements(id),
 CONSTRAINT ck_clarification_status CHECK(status IN ('OPEN','DEFERRED','ANSWERED','SUPERSEDED'))
);
CREATE INDEX ix_project_terms_status ON project_terms(project_id,status);
CREATE INDEX ix_term_usage_req ON project_term_usages(requirement_id);
CREATE INDEX ix_question_req_status ON clarification_questions(requirement_id,status);
