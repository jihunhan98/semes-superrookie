CREATE TABLE req_working_copies (
  requirement_id NUMBER PRIMARY KEY REFERENCES requirements(id),
  base_version_id NUMBER REFERENCES requirement_versions(id),
  content CLOB NOT NULL, content_hash VARCHAR2(64 CHAR) NOT NULL,
  row_version NUMBER DEFAULT 0 NOT NULL, manual_review_hash VARCHAR2(64 CHAR),
  updated_by NUMBER NOT NULL REFERENCES users(id),
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE work_bundles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requirement_id NUMBER NOT NULL REFERENCES requirements(id),
  requirement_version_id NUMBER REFERENCES requirement_versions(id),
  revision_no NUMBER NOT NULL, state VARCHAR2(20 CHAR) DEFAULT 'PLANNING' NOT NULL,
  is_current NUMBER(1) DEFAULT 1 NOT NULL, source_status VARCHAR2(20 CHAR) DEFAULT 'VERIFIED' NOT NULL,
  row_version NUMBER DEFAULT 0 NOT NULL, validation_hash VARCHAR2(64 CHAR), manifest_json CLOB,
  created_by NUMBER NOT NULL REFERENCES users(id), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  confirmed_by NUMBER REFERENCES users(id), confirmed_at TIMESTAMP,
  CONSTRAINT uq_bundle_rev UNIQUE(requirement_id, revision_no),
  CONSTRAINT ck_bundle_current CHECK(is_current IN (0,1)),
  CONSTRAINT ck_bundle_state CHECK(state IN ('PLANNING','ISSUES_READY','GENERATING','REVIEW','CONFIRMED','SUPERSEDED')),
  CONSTRAINT ck_bundle_manifest_json CHECK(manifest_json IS JSON)
);
CREATE UNIQUE INDEX uq_bundle_current ON work_bundles(CASE WHEN is_current=1 THEN requirement_id END);

