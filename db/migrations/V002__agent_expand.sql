CREATE TABLE issue_revisions (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id NUMBER NOT NULL REFERENCES dev_issues(id), revision_no NUMBER NOT NULL,
  snapshot_json CLOB NOT NULL, content_hash VARCHAR2(64 CHAR) NOT NULL,
  reason VARCHAR2(500 CHAR), actor_id NUMBER NOT NULL REFERENCES users(id),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_issue_revision UNIQUE(issue_id,revision_no), CONSTRAINT ck_issue_revision_json CHECK(snapshot_json IS JSON)
);
CREATE TABLE artifact_revisions (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artifact_id NUMBER NOT NULL REFERENCES dev_issue_artifacts(id), revision_no NUMBER NOT NULL,
  state VARCHAR2(20 CHAR) NOT NULL, content_json CLOB NOT NULL,
  content_hash VARCHAR2(64 CHAR) NOT NULL, reason VARCHAR2(500 CHAR),
  actor_id NUMBER NOT NULL REFERENCES users(id), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_artifact_revision UNIQUE(artifact_id,revision_no), CONSTRAINT ck_artifact_revision_json CHECK(content_json IS JSON)
);
CREATE TABLE issue_lineage (
  source_issue_id NUMBER NOT NULL REFERENCES dev_issues(id), target_issue_id NUMBER NOT NULL REFERENCES dev_issues(id),
  relation_type VARCHAR2(20 CHAR) NOT NULL, created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  PRIMARY KEY(source_issue_id,target_issue_id,relation_type)
);

CREATE TABLE ai_jobs (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id NUMBER NOT NULL REFERENCES projects(id), requirement_id NUMBER REFERENCES requirements(id),
  bundle_id NUMBER REFERENCES work_bundles(id), kind VARCHAR2(30 CHAR) NOT NULL,
  status VARCHAR2(20 CHAR) DEFAULT 'QUEUED' NOT NULL, idempotency_key VARCHAR2(100 CHAR) NOT NULL,
  request_hash VARCHAR2(64 CHAR) NOT NULL, requested_by NUMBER NOT NULL REFERENCES users(id),
  total_count NUMBER DEFAULT 0 NOT NULL, succeeded_count NUMBER DEFAULT 0 NOT NULL, failed_count NUMBER DEFAULT 0 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, finished_at TIMESTAMP,
  CONSTRAINT uq_ai_job_key UNIQUE(project_id,idempotency_key)
);
CREATE TABLE ai_tasks (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id NUMBER NOT NULL REFERENCES ai_jobs(id),
  task_key VARCHAR2(160 CHAR) NOT NULL, phase VARCHAR2(30 CHAR) NOT NULL,
  status VARCHAR2(20 CHAR) DEFAULT 'QUEUED' NOT NULL, depends_on_id NUMBER REFERENCES ai_tasks(id),
  attempt NUMBER DEFAULT 0 NOT NULL, max_attempts NUMBER DEFAULT 3 NOT NULL,
  next_run_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, lease_until TIMESTAMP,
  lease_token VARCHAR2(64 CHAR), worker_id VARCHAR2(100 CHAR), input_json CLOB, result_json CLOB,
  error_code VARCHAR2(80 CHAR), error_message VARCHAR2(1000 CHAR),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_ai_task_key UNIQUE(job_id,task_key),
  CONSTRAINT ck_ai_task_input_json CHECK(input_json IS JSON), CONSTRAINT ck_ai_task_result_json CHECK(result_json IS JSON)
);
CREATE INDEX ix_ai_task_claim ON ai_tasks(status,next_run_at,lease_until);

