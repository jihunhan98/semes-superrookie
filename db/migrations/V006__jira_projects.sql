-- 기존 ReqOps DB에서 이 파일 전체를 DBeaver의 "SQL 스크립트 실행"으로 실행하세요.
-- 백엔드를 종료한 뒤 실행하고, 완료 후 다시 시작하세요.
-- 현재 SQL 편집창에 선택된 스키마에 적용합니다. 기존 테이블과 데이터는 유지합니다.
-- 이미 있는 테이블은 건너뛰며, 이름이 같은 다른 종류의 객체는 삭제하지 않습니다.

DECLARE
  v_owner VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
  v_schema VARCHAR2(260);

  FUNCTION table_exists(p_name VARCHAR2) RETURN BOOLEAN IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM all_tables
    WHERE owner=v_owner AND table_name=p_name;
    RETURN n>0;
  END;

  PROCEDURE ensure_table(p_name VARCHAR2, p_definition VARCHAR2) IS
    v_other_type VARCHAR2(128);
  BEGIN
    -- USER_TABLES는 로그인 계정을 기준으로 하므로 현재 스키마와 다를 수 있습니다.
    SELECT MIN(object_type) INTO v_other_type FROM all_objects
    WHERE owner=v_owner AND object_name=p_name
      AND object_type IN ('VIEW','MATERIALIZED VIEW','SEQUENCE','SYNONYM',
                          'PACKAGE','PROCEDURE','FUNCTION','TYPE');
    IF v_other_type IS NOT NULL THEN
      RAISE_APPLICATION_ERROR(-20006, v_owner||'.'||p_name||
        ' 이름을 '||v_other_type||' 객체가 사용 중입니다. 기존 객체는 변경하지 않았습니다.');
    END IF;
    IF table_exists(p_name) THEN
      RETURN;
    END IF;
    EXECUTE IMMEDIATE 'CREATE TABLE '||v_schema||'."'||p_name||'" '||p_definition;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE=-955 THEN
        -- 동시에 실행된 다른 스크립트가 정상 테이블을 만든 경우만 건너뜁니다.
        IF NOT table_exists(p_name) THEN
          RAISE_APPLICATION_ERROR(-20007, v_owner||'.'||p_name||
            ' 생성 시 이름 충돌이 발생했습니다. 같은 이름의 객체 또는 PK/UNIQUE 인덱스를 확인해주세요.');
        END IF;
      ELSE
        RAISE;
      END IF;
  END;
BEGIN
  v_schema := '"'||REPLACE(v_owner, '"', '""')||'"';

  ensure_table('PROJECT_JIRA_TARGETS', '(
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    project_id NUMBER NOT NULL,
    base_url VARCHAR2(512 CHAR) NOT NULL,
    jira_project_key VARCHAR2(100 CHAR) NOT NULL,
    display_name VARCHAR2(200 CHAR) NOT NULL,
    issue_type_id VARCHAR2(40 CHAR),
    row_version NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT pk_project_jira_targets PRIMARY KEY(id),
    CONSTRAINT fk_jira_target_project FOREIGN KEY(project_id) REFERENCES '||v_schema||'.projects(id),
    CONSTRAINT uq_jira_target UNIQUE(project_id,base_url,jira_project_key)
  )');

  ensure_table('JIRA_ISSUE_LINKS', '(
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    target_id NUMBER NOT NULL,
    dev_issue_id NUMBER NOT NULL,
    jira_issue_key VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT pk_jira_issue_links PRIMARY KEY(id),
    CONSTRAINT fk_jira_link_target FOREIGN KEY(target_id) REFERENCES '||v_schema||'.project_jira_targets(id),
    CONSTRAINT fk_jira_link_issue FOREIGN KEY(dev_issue_id) REFERENCES '||v_schema||'.dev_issues(id),
    CONSTRAINT uq_jira_issue_link UNIQUE(target_id,dev_issue_id)
  )');
END;
/
COMMIT;
